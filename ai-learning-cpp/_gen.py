a('std::string extract_text(const std::string& line) {')
a('    auto pos = line.find("\\x22text\\x22: \\x22");')
a('    if (pos == std::string::npos) return "";')
a('    pos += 9;')
a('    std::string r; r.reserve(4096);')
a('    bool esc = false;')
a('    for (size_t i = pos; i < line.size(); ++i) {')
a('        char c = line[i];')
a('        if (esc) {')
a('            if(c==110||c==116) r+=32; else r+=c;')
a('            esc = false;')
a('        } else if (c==92) { esc=true; }')
a('        else if (c==34) break;')
a('        else { if(c==10||c==13) r+=32; else r+=c; }')
a('    }')
a('    return r;')
a('}')
