a('float cosine_sim(const std::vector<float>& a, const std::vector<float>& b) {')
a('    float dot=0,na=0,nb=0;')
a('    for(size_t i=0;i<a.size();++i){dot+=a[i]*b[i];na+=a[i]*a[i];nb+=b[i]*b[i];}')
a('    float d=std::sqrt(na)*std::sqrt(nb);')
a('    return d<1e-8f?0.0f:dot/d;')
a('}')
